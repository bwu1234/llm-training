"""Build the architecture explainer's data from the real models.

`docs/architecture/explainer.json` lists the presets (a recipe plus optional model-config
overrides) and the prose. Each preset's model is built on the meta device, which gives every
tensor a shape but no storage, so even Qwen3-0.6B builds without allocating its weights. One
forward pass records, in order:

- every module call, with module hooks;
- every call to a function of this package (such as RoPE's `apply_rope`), with `sys.monitoring`;
- every tensor operation that this package's code performs itself (a residual add, a reshape,
  a softmax), with a `TorchFunctionMode`. Operations inside a PyTorch module such as
  `nn.Linear` belong to that module's row instead.

Each call and operation also records where its tensor inputs came from: an earlier node, a
parameter or buffer, or the token IDs. That is the data flow the page draws.

A `TorchDispatchMode` checks that nothing is missed: every kernel that runs must belong to a
recorded operation or to a PyTorch module, or the trace fails.

Nothing here knows a family: the module tree, the source and the parameter counts all come from
the model itself, and the prose lives with the page. This package is outside every trainer's
resume fingerprint, and no trainer imports it.
"""

import functools
import inspect
import itertools
import json
import linecache
import re
import sys
import textwrap
from dataclasses import asdict
from pathlib import Path

import torch
import torch.nn.functional as F
from torch import nn
from torch.overrides import TorchFunctionMode
from torch.utils._python_dispatch import TorchDispatchMode

from ..lm.config import load_config
from ..model.registry import family

REPO = Path(__file__).resolve().parents[3]
PAGE_DIR = REPO / "docs" / "architecture"
CONTENT = PAGE_DIR / "explainer.json"
SPEC = PAGE_DIR / "spec.js"
COMMAND = "uv run python -m llm_training.explain"
PACKAGE = Path(__file__).resolve().parents[1]
TORCH = Path(torch.__file__).resolve().parent

# Two traced passes with different sizes; a dimension that changes between them is named.
SIZES = ({"B": 2, "T": 5}, {"B": 3, "T": 7})
SYMBOLS = {
    tuple(s["B"] for s in SIZES): "B",
    tuple(s["T"] for s in SIZES): "T",
    tuple(s["B"] * s["T"] for s in SIZES): "B·T",
}
# A module name ending in a whole numeric segment (`trf_blocks.3`, not `fc3`): a list item.
NUMBERED = re.compile(r"^((?:.*\.)?)(\d+)$")


def build_spec(content_path=CONTENT):
    content = json.loads(Path(content_path).read_text())
    base = Path(content_path).parent
    found = {"classes": {}, "functions": {}, "ops": {}}
    presets = [_preset(entry, base, found) for entry in content["presets"]]
    for preset in presets:
        _label_steps(preset["tree"], content["steps"])
        _role_keys(preset["tree"])
    for kind, entries in found.items():
        for key, info in entries.items():
            if note := content[kind].get(key):
                info["note"] = note
    return {"presets": presets, **found, "roles": content["roles"], "buffers": content["buffers"]}


def render(spec):
    return (
        f"// Generated by `{COMMAND}` from the models and explainer.json; do not edit.\n"
        "// Source excerpts below keep their files' license headers (`classes.*.header`).\n"
        f"window.ARCHITECTURE = {json.dumps(spec, indent=1, ensure_ascii=False)};\n"
    )


def write_spec(path=SPEC):
    spec = build_spec()
    Path(path).write_text(render(spec))
    return spec


def build_model(entry, base=PAGE_DIR):
    """A preset's model on the meta device, with its family and resolved model config."""
    cfg = load_config(Path(base) / entry["recipe"])
    model_family = family(cfg.model.arch)
    model_config = asdict(cfg.model) | entry.get("overrides", {})
    with torch.device("meta"):
        model = model_family.build(model_config)
    return model.eval(), model_family, model_config


def _preset(entry, base, found):
    model, model_family, model_config = build_model(entry, base)
    traces = [trace(model, size["B"], size["T"]) for size in SIZES]
    tree = _merge(*traces)
    owners = _owners(model)
    _annotate(tree, dict(model.named_modules()), owners, found)
    alias = {}
    tree = _collapse(tree, alias)
    _redirect(tree, alias)
    keys = model_family.architecture_keys + model_family.inherited_build_keys
    return {
        "id": entry["id"],
        "label": entry["label"],
        "summary": entry.get("summary", ""),
        "recipe": entry["recipe"],
        "overrides": entry.get("overrides", {}),
        "family": model_family.name,
        "config": {key: model_config[key] for key in keys if key in model_config},
        "total": sum(p.numel() for p in model.parameters()),
        "tree": tree,
    }


def trace(model, batch, tokens):
    """One meta forward pass; returns the root call with its nested calls and steps.

    Each node is a module call (`module`), a call to a function of this package (`function`),
    or a tensor operation (`op`), and `children` lists what ran inside it, in order. Every node
    has an `id`, numbered in the order the nodes start, and `inputs`: for each tensor it was
    given, the `id` of the node that produced it (`from`), the parameter or buffer (`tensor`),
    or the model's token IDs (`input`).
    """
    names = {module: name for name, module in model.named_modules()}
    tensors = {id(t): n for n, t in [*model.named_buffers(), *model.named_parameters()]}
    forwards = {type(m).forward.__code__ for m in model.modules() if _ours(type(m).forward)}
    stack = [{"children": []}]
    # The module calls in `stack`, innermost last, and whether each runs this package's code.
    modules = [("", True)]
    inside_op = [0]  # > 0 while a recorded operation runs
    kernels = [0]  # kernels dispatched so far
    ids = itertools.count()
    token_ids = torch.zeros(batch, tokens, dtype=torch.long, device="meta")
    producers = {}  # id(tensor) -> the id of the node that last returned it
    produced = []  # keeps those tensors alive, so their `id` isn't reused
    started = {}  # node id -> node

    def recording():
        return modules[-1][1] and not inside_op[0]

    def source(tensor, name=None):
        entry = {"name": name} if name else {}
        if id(tensor) in producers:
            entry["from"] = producers[id(tensor)]
        elif id(tensor) in tensors:
            entry["tensor"] = tensors[id(tensor)]
        elif tensor is token_ids:
            entry["input"] = True
        return entry

    def produce(node, value, passed=()):
        """Record `node` as the source of the tensors in `value`, except those in `passed`.

        A call that returns what a node inside it produced marks that node `returned_by` it.
        """
        started[node["id"]] = node
        for t in _tensors(value):
            if any(t is p for p in passed):
                continue
            inner = producers.get(id(t))
            if inner is not None and inner > node["id"]:  # started after `node`: inside it
                started[inner]["returned_by"] = node["id"]
            producers[id(t)] = node["id"]
            produced.append(t)

    def before(module, args, kwargs):
        named = _arguments(type(module), args, kwargs)
        call = {
            "module": names[module],
            "id": next(ids),
            "in": _shape(args),
            "inputs": [source(v, n) for n, v in named if isinstance(v, torch.Tensor)],
            "children": [],
        }
        stack[-1]["children"].append(call)
        stack.append(call)
        modules.append((call["module"], _ours(type(module).forward)))

    def after(module, args, kwargs, output):
        call = stack.pop()
        call["out"] = _shape(output)
        produce(call, output)
        modules.pop()

    def skip(code):
        return code in forwards or code.co_name.startswith("<") or not _ours(code)

    # `sys.monitoring` callbacks; DISABLE stops one code location from reporting again, so
    # PyTorch's own functions cost one call each rather than one per call.
    def start(code, offset):
        if skip(code):
            return sys.monitoring.DISABLE
        frame = sys._getframe(1)
        named = [(v, frame.f_locals[v]) for v in code.co_varnames[: code.co_argcount]]
        call = {
            "function": _function_key(frame),
            "id": next(ids),
            "line": frame.f_back.f_lineno,
            "in": _shape([v for _, v in named]),
            "inputs": [source(v, n) for n, v in named if isinstance(v, torch.Tensor)],
            "children": [],
            "frame": frame,
        }
        stack[-1]["children"].append(call)
        stack.append(call)

    def end(code, offset, value):
        if skip(code):
            return sys.monitoring.DISABLE
        if stack[-1].get("frame") is sys._getframe(1):
            call = stack.pop()
            del call["frame"]
            call["out"] = _shape(value)
            produce(call, value)

    class Steps(TorchFunctionMode):
        def __torch_function__(self, func, types, args=(), kwargs=None):
            record, before = recording(), kernels[0]
            inside_op[0] += 1
            try:
                out = func(*args, **(kwargs or {}))
            finally:
                inside_op[0] -= 1
            caller = _caller()
            # A step computes something; reading `x.shape` or `x.dtype` runs no kernel.
            computes = _shape(out) is not None or kernels[0] > before
            if record and computes and _ours(caller.f_code):
                prefix = modules[-1][0] + "." if modules[-1][0] else ""
                inputs = list(_tensors((args, kwargs)))
                step = {
                    "op": _op_key(func),
                    "id": next(ids),
                    "line": caller.f_lineno,
                    "code": linecache.getline(caller.f_code.co_filename, caller.f_lineno).strip(),
                    "in": [list(t.shape) for t in inputs],
                    "out": _shape(out),
                    "uses": [
                        tensors[id(t)].removeprefix(prefix) for t in inputs if id(t) in tensors
                    ],
                    "inputs": [source(t) for t in inputs],
                    "children": [],
                }
                stack[-1]["children"].append(step)
                # `x.to(torch.float32)` on a float32 tensor returns `x` itself: the value is
                # unchanged, so its source stays. An in-place op (`masked_fill_`) changes it.
                passed = () if step["op"].endswith("_") else inputs
                if any(t is p for t in _tensors(out) for p in passed):
                    step["unchanged"] = True
                produce(step, out, passed)
            return out

    class Unrecorded(TorchDispatchMode):
        def __torch_dispatch__(self, func, types, args=(), kwargs=None):
            kernels[0] += 1
            if recording():
                raise ValueError(f"{func} ran outside every recorded step and module")
            return func(*args, **(kwargs or {}))

    handles = []
    for module in model.modules():
        handles.append(module.register_forward_pre_hook(before, with_kwargs=True))
        handles.append(module.register_forward_hook(after, with_kwargs=True))
    tool = _monitoring_tool()
    events = sys.monitoring.events
    sys.monitoring.register_callback(tool, events.PY_START, start)
    sys.monitoring.register_callback(tool, events.PY_RETURN, end)
    try:
        with torch.no_grad(), Unrecorded(), Steps():
            sys.monitoring.set_events(tool, events.PY_START | events.PY_RETURN)
            model(token_ids)
    finally:
        sys.monitoring.set_events(tool, events.NO_EVENTS)
        sys.monitoring.free_tool_id(tool)
        for handle in handles:
            handle.remove()
    (root,) = stack[0]["children"]
    return root


def _arguments(cls, args, kwargs):
    """A module call's arguments as (parameter name, value) pairs."""
    try:
        bound = _forward_signature(cls).bind(None, *args, **kwargs)
    except TypeError:
        return [(None, v) for v in [*args, *kwargs.values()]]
    return list(bound.arguments.items())[1:]


@functools.cache
def _forward_signature(cls):
    return inspect.signature(cls.forward)


def _monitoring_tool():
    """Claim a free `sys.monitoring` tool ID; a debugger or coverage tool may hold others."""
    for tool in range(6):
        if sys.monitoring.get_tool(tool) is None:
            sys.monitoring.use_tool_id(tool, "llm_training.explain")
            return tool
    raise RuntimeError("every sys.monitoring tool ID is in use")


def _ours(code):
    """Whether a code object (or a function) is this package's, outside the explainer."""
    return _in_package(getattr(code, "__code__", code).co_filename)


@functools.cache
def _in_package(filename):
    path = Path(filename).resolve()
    return path.is_relative_to(PACKAGE) and not path.is_relative_to(Path(__file__).parent)


@functools.cache
def _in_torch(filename):
    return Path(filename).resolve().is_relative_to(TORCH)


def _caller():
    """The first frame outside PyTorch and this module: the code that made the call."""
    frame = sys._getframe(2)
    while _in_torch(frame.f_code.co_filename):
        frame = frame.f_back
    return frame


def _tensors(value):
    if isinstance(value, torch.Tensor):
        yield value
    elif isinstance(value, (tuple, list)):
        for item in value:
            yield from _tensors(item)
    elif isinstance(value, dict):
        for item in value.values():
            yield from _tensors(item)


def _function_key(frame):
    return f"{frame.f_globals['__name__']}.{frame.f_code.co_qualname}"


def _op_key(func):
    """The public name of an intercepted function: `torch.Tensor.view`, `torch.triu`, …"""
    name = func.__name__
    if name == "__get__":  # a property such as `x.T`
        return f"torch.Tensor.{func.__self__.__name__}"
    if getattr(F, name, None) is func:
        return f"torch.nn.functional.{name}"
    if getattr(torch, name, None) is func:
        return f"torch.{name}"
    if func.__qualname__.split(".")[0] in ("Tensor", "TensorBase"):
        return f"torch.Tensor.{name}"
    raise ValueError(f"no public name for {func!r}")


def _shape(value):
    """The shape of the first tensor in `value` (a module's inputs or outputs)."""
    if isinstance(value, torch.Tensor):
        return list(value.shape)
    if isinstance(value, (tuple, list)):
        for item in value:
            if (shape := _shape(item)) is not None:
                return shape
    return None


def _merge(first, second):
    """Combine two traces: equal dimensions stay numbers, changed ones become B, T or B·T."""
    fixed = {k: v for k, v in first.items() if k not in ("in", "out", "children")}
    if fixed != {k: v for k, v in second.items() if k not in ("in", "out", "children")} or len(
        first["children"]
    ) != len(second["children"]):
        raise ValueError(f"the forward pass depends on the input size at {fixed}")
    if "op" in first:
        inputs = [_symbolic(a, b) for a, b in zip(first["in"], second["in"], strict=True)]
    else:
        inputs = _symbolic(first["in"], second["in"])
    return fixed | {
        "in": inputs,
        "out": _symbolic(first["out"], second["out"]),
        "children": [_merge(a, b) for a, b in zip(first["children"], second["children"])],
    }


def _symbolic(first, second):
    if first is None or second is None:
        return None
    named = []
    for a, b in zip(first, second, strict=True):
        if a == b:
            named.append(a)
        elif (a, b) in SYMBOLS:
            named.append(SYMBOLS[(a, b)])
        else:
            raise ValueError(f"cannot name a dimension that is {a}, then {b}")
    return named


def _owners(model):
    """Each parameter's first name; a tied parameter belongs to the module registered first."""
    return {id(p): name for name, p in model.named_parameters()}


def _annotate(call, modules, owners, found):
    """Add classes, parameters and totals to module calls; register functions and ops."""
    if "module" not in call:
        if "op" in call:
            found["ops"].setdefault(call["op"], _op_info(call["op"]))
        else:
            found["functions"].setdefault(call["function"], _function_info(call["function"]))
        for child in call["children"]:
            _annotate(child, modules, owners, found)
        call["total"] = sum(c["total"] for c in call["children"])
        return
    module = modules[call["module"]]
    prefix = f"{call['module']}." if call["module"] else ""
    call["class"] = _class_key(type(module), found["classes"])
    persistent = {k for k in module.state_dict(keep_vars=True) if "." not in k}
    call["params"] = [
        _parameter(name, p, prefix, owners) for name, p in module.named_parameters(recurse=False)
    ]
    call["buffers"] = [
        {"name": name, "shape": list(b.shape), "persistent": name in persistent}
        for name, b in module.named_buffers(recurse=False)
    ]
    call["total"] = sum(p.numel() for p in module.parameters() if owners[id(p)].startswith(prefix))
    for child in call["children"]:
        _annotate(child, modules, owners, found)


def _parameter(name, param, prefix, owners):
    entry = {"name": name, "shape": list(param.shape), "count": param.numel()}
    if owners[id(param)] != prefix + name:
        entry["tied_to"] = owners[id(param)]
    return entry


def _class_key(cls, classes):
    public = getattr(nn, cls.__name__, None)
    key = f"torch.nn.{cls.__name__}" if public is cls else f"{cls.__module__}.{cls.__qualname__}"
    if key not in classes:
        classes[key] = _class_info(cls, public is cls)
    return key


def _class_info(cls, is_torch):
    if is_torch:
        url = f"https://docs.pytorch.org/docs/stable/generated/torch.nn.{cls.__name__}.html"
        return {"name": cls.__name__, "docs": url}
    path = Path(inspect.getsourcefile(cls)).resolve()
    lines = path.read_text().splitlines()
    forward, forward_line = inspect.getsourcelines(cls.forward)
    return {
        "name": cls.__name__,
        "path": path.relative_to(REPO).as_posix(),
        "line": inspect.getsourcelines(cls)[1],
        "header": list(_leading_comments(lines)),
        "forward": {"line": forward_line, "code": textwrap.dedent("".join(forward))},
    }


def _function_info(key):
    module_name, _, qualname = key.partition(".")
    while qualname and module_name + "." + qualname.split(".")[0] in sys.modules:
        head, _, qualname = qualname.partition(".")
        module_name += "." + head
    function = sys.modules[module_name]
    for part in qualname.split("."):
        function = getattr(function, part)
    path = Path(inspect.getsourcefile(function)).resolve()
    source, line = inspect.getsourcelines(function)
    return {
        "name": function.__name__,
        "path": path.relative_to(REPO).as_posix(),
        "line": line,
        "header": list(_leading_comments(path.read_text().splitlines())),
        "code": textwrap.dedent("".join(source)),
    }


def _op_info(key):
    name = key.rsplit(".", 1)[1]
    if name.startswith("__"):  # `x[...]` and other operators without a docs page of their own
        return {"name": name.strip("_")}
    return {"name": name, "docs": f"https://docs.pytorch.org/docs/stable/generated/{key}.html"}


def _leading_comments(lines):
    for line in lines:
        if not line.startswith("#"):
            return
        yield line


def _label_steps(node, labels, container=None):
    """Give each operation the label `explainer.json` gives its source line.

    `labels` maps a class or function to fragments of its source lines; a fragment's label is
    a string, or a mapping from operation name for lines that do several things.
    """
    if "op" in node:
        for fragment, label in labels.get(container, {}).items():
            if fragment in node["code"]:
                label = (
                    label.get(node["op"].rsplit(".", 1)[1]) if isinstance(label, dict) else label
                )
                if label:
                    node["label"] = label
                break
    inner = node["class"] if "module" in node else node.get("function", container)
    for child in node["children"]:
        _label_steps(child, labels, inner)


def _role_keys(node, anchor=None):
    """Key each module call's role by its path from the nearest module of this package.

    `ff.layers.0` inside a GPT-2 `FeedForward` becomes `…FeedForward.layers.0`: its parent, an
    `nn.Sequential`, says nothing about it. A folded run of blocks drops its index.
    """
    if "module" in node and anchor is not None:
        prefix = anchor["module"] + "." if anchor["module"] else ""
        path = node["module"].removeprefix(prefix)
        if node.get("repeat", 1) > 1:
            path = NUMBERED.match(path)[1].rstrip(".")
        node["role"] = f"{anchor['class']}.{path}"
    if "module" in node and not node["class"].startswith("torch.nn."):
        anchor = node
    for child in node["children"]:
        _role_keys(child, anchor)


def _collapse(call, alias):
    """Fold consecutive identical numbered siblings (`blocks.0`, `blocks.1`, …) into one.

    `alias` maps the id of every node folded away to the id of the node that now stands for it.
    """
    children = []
    for child in [_collapse(c, alias) for c in call["children"]]:
        previous = children[-1] if children else None
        if previous and _next_in_run(previous, child):
            previous["repeat"] += 1
            previous["last"] = child["module"]
            _alias(child, previous, alias)
            _mark_first_copy(child, previous, alias, previous["id"])
            if "returned_by" in child:  # an `nn.Sequential` returns its last block's output
                previous["returned_by"] = child["returned_by"]
        else:
            children.append(child | {"repeat": 1})
    return call | {"children": children}


def _alias(folded, kept, alias):
    alias[folded["id"]] = kept["id"]
    for a, b in zip(folded["children"], kept["children"], strict=True):
        _alias(a, b, alias)


def _mark_first_copy(folded, kept, alias, run):
    """Mark inputs that only the first copy reads, because later copies read the copy before.

    In a run of blocks, block 0's residual input is the embedding and block k's is block k − 1,
    whose id `alias` maps to the run's id.
    """
    for a, b in zip(folded["children"], kept["children"], strict=True):
        _mark_first_copy(a, b, alias, run)
    for a, b in zip(folded["inputs"], kept["inputs"], strict=True):
        source = alias.get(a["from"], a["from"]) if "from" in a else None
        if source is None or source == b.get("from"):
            continue
        if source != run:
            raise ValueError(f"copies of a folded run read different sources: {a}, {b}")
        b["first_copy"] = True


def _redirect(node, alias):
    """Point inputs that came from a folded node at the node that stands for it."""
    for entry in node["inputs"]:
        if "from" in entry:
            entry["from"] = alias.get(entry["from"], entry["from"])
    if "returned_by" in node:
        node["returned_by"] = alias.get(node["returned_by"], node["returned_by"])
    for child in node["children"]:
        _redirect(child, alias)


def _last_id(node):
    return max([node["id"], *(_last_id(c) for c in node["children"])])


def _next_in_run(previous, child):
    if "module" not in previous or "module" not in child:
        return False
    a, b = NUMBERED.match(previous.get("last", previous["module"])), NUMBERED.match(child["module"])
    return (
        a is not None
        and b is not None
        and a[1] == b[1]
        and int(b[2]) == int(a[2]) + 1
        and _signature(previous) == _signature(child)
    )


def _signature(call):
    """A call's structure with its own name factored out, so repeated blocks compare equal."""
    own, first, last = call["module"], call["id"], _last_id(call)

    def ref(i):
        return i - first if first <= i <= last else "outside"

    def entry(e):
        """An input with ids relative to the call; the block before differs, so it's elided."""
        e = {k: v for k, v in e.items() if k != "first_copy"}  # set while folding this run
        if "from" in e:
            e = e | {"from": ref(e["from"])}
        if "tensor" in e:
            e = e | {"tensor": e["tensor"].removeprefix(own + ".")}
        return e

    def strip(node):
        stripped = node | {"children": [strip(c) for c in node["children"]]}
        stripped["id"] = node["id"] - first
        stripped["inputs"] = [entry(e) for e in node["inputs"]]
        if "returned_by" in node:
            stripped["returned_by"] = ref(node["returned_by"])
        for key in ("module", "last"):
            if key in node:
                stripped[key] = node[key].removeprefix(own)
        if "params" in node:
            stripped["params"] = [
                {k: v for k, v in p.items() if k != "tied_to"} for p in node["params"]
            ]
        return stripped

    # `repeat` and `last` are the run's own bookkeeping, set on `previous` but not on `child`;
    # `returned_by` is about the caller, which returns only the last block's output.
    top = {k: v for k, v in strip(call).items() if k not in ("repeat", "last", "returned_by")}
    return json.dumps(top)
